const { _electron: electron } = require('playwright');
const fs = require('fs'), path = require('path'), os = require('os');
const SIM = __dirname; const ROOT = path.resolve(__dirname, '..', '..'); const res = []; const ok = (n, c, x = '') => { res.push(c); console.log(c ? 'PASS' : 'FAIL', n, c ? '' : x); };
(async () => {
  fs.writeFileSync(path.join(SIM, 'state.json'), JSON.stringify({ paired: true, connected: ['127.0.0.1:41567'], mdnsTwin: false }));
  for (const f of ['versions.json', 'packages.txt', 'device.log']) try { fs.unlinkSync(path.join(SIM, f)); } catch {}
  const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'adbc7-'));
  fs.writeFileSync(path.join(userData, 'settings.json'), JSON.stringify({ lang: process.env.HE ? 'he' : 'en', apps: { folders: [path.join(SIM, 'apkdir')] } }));
  const app = await electron.launch({ args: [ROOT, '--no-sandbox', `--user-data-dir=${userData}`], executablePath: require(path.join(ROOT, 'node_modules', 'electron')), env: { ...process.env, ADB_PATH: path.join(SIM, 'adb'), SIM } });
  const p = await app.firstWindow(); const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.setViewportSize({ width: 1180, height: 900 }).catch(() => {});
  await p.waitForSelector('.switcher.live', { timeout: 15000 }); await p.waitForTimeout(1200);
  await p.click('.rail-btn[data-page="apps"]'); await p.waitForSelector('.app-row');
  await p.evaluate(() => { window.__t = []; new MutationObserver(() => { const t = document.querySelector('#toast .msg'); if (t) window.__t.push(t.textContent); }).observe(document.getElementById('toast'), { childList: true, subtree: true }); });
  await p.waitForSelector('#updBanner:not(.hidden)', { timeout: 15000 }).catch(() => {});
  const bar = await p.textContent('#foldersBar');
  ok('folder bar shows the folder and 2 apps (duplicates merged)', /apkdir/.test(bar) && /2 apps found|נמצאו 2/.test(bar), bar);
  const ban = await p.textContent('#updBanner').catch(() => '');
  ok('update banner for the older installed app', /1 update|עדכון אחד/.test(ban) && /Termux/i.test(ban), ban);
  const btn = await p.$('.app-row[data-p="com.termux"] [data-a="update"]');
  ok('row has Update · v0.118.3', !!btn && /0\.118\.3/.test(await btn.textContent()));
  ok('no update for apps without a newer file', !(await p.$('.app-row[data-p="app.relink"] [data-a="update"]')));
  await p.screenshot({ path: path.join(SIM, 'shots', `70-folder-updates${process.env.HE ? '-he' : ''}.png`) });
  await p.click('#appTabs [data-t="library"]'); await p.waitForTimeout(800);
  const lib = await p.textContent('#libList');
  ok('folder apps listed in the library (not installed one too)', /NewPipe/.test(lib) && /Termux/.test(lib), lib.slice(0, 200));
  ok('library card marks the update', !!(await p.$('.lib-card.has-upd[data-pkg="com.termux"]')));
  await p.screenshot({ path: path.join(SIM, 'shots', `71-folder-library${process.env.HE ? '-he' : ''}.png`) });
  await p.click('#appTabs [data-t="device"]'); await p.waitForTimeout(300);
  await p.click('#updAll');
  for (let i = 0; i < 50 && !(await p.evaluate(() => window.__t.some((x) => /Installed|הותקן|fail/i.test(x)))); i++) await p.waitForTimeout(300);
  ok('Update all installs it', (await p.evaluate(() => window.__t)).some((x) => /Installed|הותקן/.test(x)), JSON.stringify(await p.evaluate(() => window.__t)));
  await p.waitForTimeout(3000);
  ok('banner gone after updating', await p.$eval('#updBanner', (b) => b.classList.contains('hidden')));
  ok('no UI errors', errs.length === 0, JSON.stringify(errs));
  await app.close();
  console.log(`${res.filter(Boolean).length}/${res.length} passed`);
})().catch((e) => { console.error('CRASH', e); process.exit(1); });
