const { _electron: electron } = require('playwright');
const fs = require('fs'), path = require('path'), os = require('os');
const SIM = __dirname; const ROOT = path.resolve(__dirname, '..', '..'); const res = []; const ok = (n, c, x = '') => { res.push(c); console.log(c ? 'PASS' : 'FAIL', n, x); };
(async () => {
  fs.writeFileSync(path.join(SIM, 'state.json'), JSON.stringify({ paired: true, connected: ['127.0.0.1:41567'], mdnsTwin: true }));
  const userData = fs.mkdtempSync(path.join(os.tmpdir(), 'adbc2-'));
  const app = await electron.launch({ args: [ROOT, '--no-sandbox', `--user-data-dir=${userData}`], executablePath: require(path.join(ROOT, 'node_modules', 'electron')), env: { ...process.env, ADB_PATH: path.join(SIM, 'adb'), SIM } });
  const p = await app.firstWindow(); const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.waitForSelector('.switcher.live', { timeout: 15000 }); await p.waitForTimeout(1200);
  await p.click('.rail-btn[data-page="shell"]'); await p.waitForSelector('#cmdInput'); await p.waitForTimeout(2500);
  const term = () => p.evaluate(() => { const t = []; document.querySelectorAll('.xterm-rows > div').forEach((d) => t.push(d.textContent)); return t.join('\n'); });
  const allTerm = async () => { await p.click('#shCopy'); return p.evaluate(() => navigator.clipboard.readText()).catch(() => ''); };
  const runBox = async (t, wait = 1500) => { await p.fill('#cmdInput', t); await p.press('#cmdInput', 'Enter'); await p.waitForTimeout(wait); };
  // long command
  const longArg = 'x'.repeat(1400);
  await p.fill('#cmdInput', `echo START-LONG; echo ${longArg} | wc -c; echo END-LONG`);
  const h = await p.$eval('#cmdInput', (i) => i.offsetHeight);
  await p.dispatchEvent('#cmdInput', 'input');
  const h2 = await p.$eval('#cmdInput', (i) => i.offsetHeight);
  ok('command box grows to show the whole long command', h2 > 60, `${h}→${h2}px`);
  await p.press('#cmdInput', 'Enter'); await p.waitForTimeout(2500);
  let t = await term();
  ok('1,400-char command runs completely', /START-LONG/.test(t) && /\b1401\b/.test(t) && /END-LONG/.test(t), t.replace(/\s+/g, ' ').slice(-160));
  ok('the full long command is shown (wrapped) in the terminal', (t.match(/x{20,}/g) || []).join('').length >= 1300);
  await runBox('echo one\necho two\ncd /sdcard && pwd');
  t = await term();
  ok('multi-line paste runs every line (and cd persists)', /\bone\b/.test(t) && /\btwo\b/.test(t) && /root\/sdcard/.test(t), t.replace(/\s+/g, ' ').slice(-140));
  await runBox('pwd'); t = await term();
  ok('working folder kept between commands', (t.match(/root\/sdcard/g) || []).length >= 2);
  await runBox('adb shell getprop ro.product.model adb shell echo SECOND-OK');
  t = await term();
  ok('several "adb shell …" on one line', /SM-R920/.test(t) && /SECOND-OK/.test(t));
  await runBox('adb devices', 2500); t = await term();
  ok('"adb devices" runs on the computer', /List of devices/.test(t));
  await p.click('#cmdInput'); await p.press('#cmdInput', 'ArrowUp');
  ok('↑ recalls history', (await p.inputValue('#cmdInput')) === 'adb devices');
  await p.press('#cmdInput', 'ArrowUp');
  ok('↑ again goes further back', /SECOND-OK/.test(await p.inputValue('#cmdInput')));
  await p.fill('#cmdInput', 'dumpsys bat'); await p.press('#cmdInput', 'Tab');
  ok('Tab completes words', (await p.inputValue('#cmdInput')) === 'dumpsys battery ');
  await p.fill('#cmdInput', 'am force-stop com.exa'); await p.press('#cmdInput', 'Tab');
  ok('Tab completes package names', /com\.example\.watchface/.test(await p.inputValue('#cmdInput')), await p.inputValue('#cmdInput'));
  await p.fill('#cmdInput', '');
  await p.click('.xterm'); await p.keyboard.type('echo TYPED-DIRECT'); await p.keyboard.press('Enter'); await p.waitForTimeout(1200);
  ok('typing directly in the terminal works', /TYPED-DIRECT\s/.test(await term()));
  await p.click('.xterm'); await p.keyboard.type('adb shell echo FIXED-DIRECT'); await p.keyboard.press('Enter'); await p.waitForTimeout(1500);
  t = await term(); ok('"adb shell" typed in the terminal is fixed', /FIXED-DIRECT/.test(t) && !/adb: (not found|inaccessible)/.test(t));
  await p.screenshot({ path: path.join(SIM, 'shots', '30-shell.png') });
  ok('history saved', ((await p.evaluate(() => window.api.settingsGet())).shellHistory || []).length >= 4);
  ok('no UI errors', errs.length === 0, JSON.stringify(errs));
  await app.close();
  console.log(`${res.filter(Boolean).length}/${res.length} passed`);
})().catch((e) => { console.error('CRASH', e); process.exit(1); });
